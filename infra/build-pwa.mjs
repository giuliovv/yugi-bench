import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../web");
const files = ["index.html", "play.html", "bot.html", "app.js", "styles.css",
  "pwa.js", "manifest.webmanifest", "icon.svg", "icon-192.png", "icon-512.png"];
const hash = createHash("sha256");
for (const file of files) hash.update(readFileSync(resolve(root, file)));
const version = hash.digest("hex").slice(0, 16);

const sw = `// Generated by infra/build-pwa.mjs. Do not edit web/sw.js directly.
const CACHE = "yugi-bench-${version}";
const FILES = ${JSON.stringify(["./", ...files.map(file => `./${file}`)])};
const PATHS = new Set(FILES.map(file => new URL(file, self.registration.scope).pathname));

self.addEventListener("install", event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", event => {
  event.waitUntil(Promise.all([
    caches.keys().then(keys => Promise.all(keys.filter(key => key.startsWith("yugi-bench-") && key !== CACHE)
      .map(key => caches.delete(key)))),
    self.clients.claim()
  ]));
});

self.addEventListener("fetch", event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin || !PATHS.has(url.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    try {
      const response = await fetch(request);
      if (response.ok) await cache.put(request, response.clone());
      return response;
    } catch (error) {
      const cached = await cache.match(request, { ignoreSearch: true });
      if (cached) return cached;
      if (request.mode === "navigate") {
        const home = await cache.match(new URL("./index.html", self.registration.scope));
        if (home) return home;
      }
      throw error;
    }
  })());
});
`;

writeFileSync(resolve(root, "sw.js"), sw);
console.log(`web/sw.js: ${version}`);
